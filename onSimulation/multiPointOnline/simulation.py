"""
Synthetic experiment generation driven by an OpenGATE relative-response table.

This module does not contain an analytic detector forward model. It uses the
Monte Carlo response table H(relative source position, detector orientation,
channel) generated by OpenGATE and interpolates it for the requested trajectory.
"""

import numpy as np
import torch

from common.geometry import (
    derive_search_volume_from_trajectory_cylinder,
    EPS,
    make_detector_geometry,
    make_detector_trajectory,
)
from reconstruction_objective import build_system_matrix


def gaussian_source_components(
    position,
    emission_count,
    spread_cm,
    component_spacing_cm=0.25,
    edge_relative_activity=0.25,
):
    """
    Approximate a diffuse source by deterministic point-source components.

    emission_count is the number of emitted photons represented by this source
    during one measurement. Component emission counts sum to emission_count.
    """
    position = np.asarray(position, dtype=float)
    emission_count = float(emission_count)
    spread_cm = float(spread_cm)
    component_spacing_cm = float(component_spacing_cm)
    if component_spacing_cm <= EPS:
        raise ValueError("component_spacing_cm must be > 0.")
    edge_relative_activity = float(edge_relative_activity)
    if not 0.0 < edge_relative_activity < 1.0:
        raise ValueError("edge_relative_activity must be between 0 and 1.")
    if spread_cm <= EPS:
        return [{"position": position.copy(), "emission_count": emission_count, "weight": 1.0}]

    radius_cm = spread_cm
    sigma_cm = radius_cm / np.sqrt(-2.0 * np.log(edge_relative_activity))
    max_offset_steps = int(np.ceil(radius_cm / component_spacing_cm))
    axis_offsets = (
        np.arange(-max_offset_steps, max_offset_steps + 1, dtype=float)
        * component_spacing_cm
    )
    axis_offsets = axis_offsets[np.abs(axis_offsets) <= radius_cm + EPS]

    offsets = []
    weights = []
    for x_offset in axis_offsets:
        for y_offset in axis_offsets:
            for z_offset in axis_offsets:
                offset = np.array([x_offset, y_offset, z_offset], dtype=float)
                radius_squared = float(np.dot(offset, offset))
                if radius_squared > radius_cm**2:
                    continue
                normalized_radius_squared = radius_squared / max(sigma_cm**2, EPS)
                offsets.append(offset)
                weights.append(float(np.exp(-0.5 * normalized_radius_squared)))

    weights = np.asarray(weights, dtype=float)
    weights /= max(float(np.sum(weights)), EPS)
    return [
        {
            "position": position + offset,
            "emission_count": emission_count * weight,
            "weight": weight,
        }
        for offset, weight in zip(offsets, weights)
    ]


def expected_counts_multi_source(
    sources,
    rotations,
    translations,
    backgrounds,
    relative_response_table_path,
    response_column="response_weighted_probability",
    response_scale=1.0,
):
    """Expected detector counts from sources using the OpenGATE response table."""
    rotations = np.asarray(rotations, dtype=float)
    translations = np.asarray(translations, dtype=float)
    backgrounds = np.asarray(backgrounds, dtype=float)
    mean_counts = np.broadcast_to(backgrounds, (len(translations), len(backgrounds))).copy()

    component_positions = []
    component_emissions = []
    for source in sources:
        components = source.get("components")
        if components is None:
            components = gaussian_source_components(
                position=source["position"],
                emission_count=source["emission_count"],
                spread_cm=source.get("spread_cm", 0.0),
            )

        for component in components:
            component_positions.append(np.asarray(component["position"], dtype=float))
            component_emissions.append(float(component["emission_count"]))

    if not component_positions:
        return mean_counts

    system_matrix = build_system_matrix(
        candidate_positions=np.asarray(component_positions, dtype=float),
        rotations=rotations,
        translations=translations,
        relative_response_table_path=relative_response_table_path,
        response_column=response_column,
        activity_to_emission_scale=response_scale,
    )
    emission_vector = torch.as_tensor(
        component_emissions,
        dtype=system_matrix.dtype,
        device=system_matrix.device,
    )
    source_counts = (system_matrix @ emission_vector).reshape(mean_counts.shape)
    mean_counts += source_counts.detach().cpu().numpy()

    return mean_counts


def generate_synthetic_dataset(
    num_measurements,
    seed,
    orientation_mode,
    fixed_view_direction,
    source_specs,
    num_channels,
    diode_pitch,
    background_mean_per_second,
    background_channel_std_per_second,
    measurement_duration_seconds,
    trajectory_center,
    search_radius,
    cylinder_height,
    trajectory_mode,
    angular_jitter_deg,
    lateral_span,
    vertical_span,
    base_distance,
    distance_span,
    orbit_radius,
    orbit_radius_span,
    orbit_angle_span_deg,
    orbit_start_angle_deg,
    orbit_vertical_span,
    fixed_sweep_z_range_deg,
    fixed_sweep_x_range_deg,
    relative_response_table_path,
    response_column="response_weighted_probability",
    response_scale=1.0,
):
    """
    Generate one synthetic multi-source experiment from OpenGATE H.

    source_specs use emission_rate_per_second, not analytic activity. The stored
    source emission_count is emission_rate_per_second * measurement_duration.
    """
    rng = np.random.default_rng(seed)

    geometry = make_detector_geometry(num_channels=num_channels, diode_pitch=diode_pitch)
    num_channels = len(geometry["diode_positions_local"])

    if not source_specs:
        raise ValueError("source_specs must contain at least one source.")

    measurement_duration_seconds = float(measurement_duration_seconds)
    if measurement_duration_seconds <= 0.0:
        raise ValueError("measurement_duration_seconds must be > 0.")

    true_sources = []
    for source_index, source in enumerate(source_specs, start=1):
        if "emission_rate_per_second" not in source:
            raise KeyError(
                f"source_specs[{source_index}] must define emission_rate_per_second."
            )
        emission_rate_per_second = float(source["emission_rate_per_second"])
        if emission_rate_per_second < 0.0:
            raise ValueError("emission_rate_per_second must be >= 0.")
        spread_cm = float(source.get("spread_cm", 0.0))
        if spread_cm < 0.0:
            raise ValueError("source spread_cm must be >= 0.")
        emission_count = emission_rate_per_second * measurement_duration_seconds
        components = gaussian_source_components(
            position=source["position"],
            emission_count=emission_count,
            spread_cm=spread_cm,
        )
        true_sources.append(
            {
                "position": np.array(source["position"], dtype=float),
                "emission_rate_per_second": emission_rate_per_second,
                "strength_per_second": emission_rate_per_second,
                "emission_count": emission_count,
                "strength": emission_count,
                "spread_cm": spread_cm,
                "components": components,
            }
        )

    if trajectory_center is None:
        raise ValueError("trajectory_center must be provided explicitly.")
    trajectory_center = np.array(trajectory_center, dtype=float)

    background_mean = float(background_mean_per_second) * measurement_duration_seconds
    background_channel_std = float(background_channel_std_per_second) * measurement_duration_seconds
    true_backgrounds = rng.normal(
        loc=background_mean,
        scale=background_channel_std,
        size=num_channels,
    )

    rotations, translations = make_detector_trajectory(
        geometry=geometry,
        trajectory_center=trajectory_center,
        num_measurements=num_measurements,
        rng=rng,
        trajectory_mode=trajectory_mode,
        angular_jitter_deg=angular_jitter_deg,
        lateral_span=lateral_span,
        vertical_span=vertical_span,
        base_distance=base_distance,
        distance_span=distance_span,
        orbit_radius=orbit_radius,
        orbit_radius_span=orbit_radius_span,
        orbit_angle_span_deg=orbit_angle_span_deg,
        orbit_start_angle_deg=orbit_start_angle_deg,
        orbit_vertical_span=orbit_vertical_span,
        orientation_mode=orientation_mode,
        fixed_view_direction=fixed_view_direction,
        fixed_sweep_z_range_deg=fixed_sweep_z_range_deg,
        fixed_sweep_x_range_deg=fixed_sweep_x_range_deg,
    )
    search_volume = derive_search_volume_from_trajectory_cylinder(
        trajectory_center=trajectory_center,
        search_radius=search_radius,
        cylinder_height=cylinder_height,
    )

    mean_counts = expected_counts_multi_source(
        sources=true_sources,
        rotations=rotations,
        translations=translations,
        backgrounds=true_backgrounds,
        relative_response_table_path=relative_response_table_path,
        response_column=response_column,
        response_scale=response_scale,
    )
    noisy_counts = rng.poisson(mean_counts).astype(float)

    return {
        "counts": noisy_counts,
        "mean_counts": mean_counts,
        "rotations": rotations,
        "translations": translations,
        "geometry": geometry,
        "true_sources": true_sources,
        "trajectory_center": trajectory_center,
        "search_min": np.array(search_volume["search_min"], dtype=float),
        "search_max": np.array(search_volume["search_max"], dtype=float),
        "search_radius": search_volume["search_radius"],
        "cylinder_height": search_volume["cylinder_height"],
        "true_backgrounds": true_backgrounds,
        "relative_response_table_path": str(relative_response_table_path),
        "response_column": str(response_column),
        "response_scale": float(response_scale),
        "measurement_duration_seconds": measurement_duration_seconds,
        "background_mean_per_second": background_mean_per_second,
        "background_mean": background_mean,
        "background_channel_std_per_second": background_channel_std_per_second,
        "background_channel_std": background_channel_std,
        "trajectory_mode": trajectory_mode,
    }
